_TABLE_MAP = {code: (name, msg) for code, name, msg in _TABLE}


def describe(code: int) -> str:
    """Human-readable description: "ERR_AUTH_FAILED (9): Authentication failure"."""
    entry = _TABLE_MAP.get(code)
    if entry:
        return f"{entry[0]} ({code}): {entry[1]}"
    return f"ERR_{code} ({code}): Unknown server error"


def info(code: int) -> tuple[str, str] | None:
    """(name, message) for a code, or None for code 0 (no error)."""
    if code == 0:
        return None
    return _TABLE_MAP.get(code)